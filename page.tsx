function Survey({ p, set, onExit, onFinish }: { p: Profile; set: SetFn; onExit: () => void; onFinish: () => void }) {
  const [step, setStep] = useState(0);
  const [showErr, setShowErr] = useState(false);
  const last = STEP_TITLES.length - 1;
  const headRef = useRef<HTMLHeadingElement>(null);
  useEffect(() => headRef.current?.focus(), [step]);

  const errs = requiredErrors(p);
  const hasErrs = Object.keys(errs).length > 0;

  const next = (e: FormEvent) => {
    e.preventDefault();
    // The basics (step 0) are required. Everything after that is optional.
    if (step === 0 && hasErrs) {
      setShowErr(true);
      return;
    }
    if (step < last) setStep(step + 1);
    else if (hasErrs) {
      setShowErr(true);
      setStep(0);
    } else onFinish();
  };

  const summary: [string, string, number][] = [
    ["Name", p.name || "Not shared", 0],
    ["Studies", [p.year, p.major, p.spec, p.gradYear && `graduating ${p.gradYear}`].filter(Boolean).join(", ") || "Not shared", 0],
    ["Region", p.region || "Not shared", 0],
    ["Outcomes", [...p.vision.filter((v) => v !== "Other"), p.visionOther].filter(Boolean).join(", ") || "Not shared", 1],
    ["Interests", [...p.interests.filter((v) => v !== "Other"), p.interestsOther].filter(Boolean).join(", ") || "Not shared", 2],
    ["Activities", p.activities.join(", ") || "Not shared", 2],
    ["Experience", p.experience.join(", ") || "Not shared", 3],
    ["Challenges", p.challenges.join(", ") || "Not shared", 3],
    ["Career direction", isExploring(p) ? `Exploring first${p.careers ? ` (curious about ${p.careers})` : ""}` : p.careers, 4],
    ["CV", p.cvName ?? "None yet. Building a first CV will be a milestone.", 5],
  ];

  return (
    <section className="flex min-h-screen items-center justify-center px-6 pb-24 pt-20">
      <form onSubmit={next} noValidate className={`${card} w-full max-w-2xl p-6 md:p-8`}>
        <p className="text-sm font-bold text-[var(--muted)]" aria-live="polite">Step {step + 1} of {STEP_TITLES.length}</p>
        <div className="mt-2 h-1.5 overflow-hidden rounded-full bg-[var(--tint)]" role="progressbar" aria-valuemin={1} aria-valuemax={STEP_TITLES.length} aria-valuenow={step + 1} aria-label="Survey progress">
          <div className="h-full rounded-full bg-[var(--accent)] transition-[width] duration-300" style={{ width: `${((step + 1) / STEP_TITLES.length) * 100}%` }} />
        </div>
        <h2 ref={headRef} tabIndex={-1} className="mt-6 text-2xl font-extrabold outline-none md:text-3xl">{STEP_TITLES[step]}</h2>
        {step === 0 && <p className="mt-1 text-sm text-[var(--muted)]">You do not need to have everything figured out. Only the basics below are required. Everything after this step is optional.</p>}
        {step === last && showErr && hasErrs && <p role="alert" className="mt-2 text-sm font-semibold text-[#E5484D]">Some basics are missing. Go back to step 1 to fill them in.</p>}
        <div className="mt-6">
          {step < last ? (
            <div key={step} className="rise"><StepBody step={step} p={p} set={set} errors={showErr ? errs : {}} /></div>
          ) : (
            <dl className="divide-y divide-[var(--line)] text-sm">
              {summary.map(([k, v, s]) => (
                <div key={k} className="flex items-start justify-between gap-4 py-2.5">
                  <div><dt className="font-bold">{k}</dt><dd className="mt-0.5 text-[var(--muted)]">{v}</dd></div>
                  <button type="button" onClick={() => setStep(s)} className={`shrink-0 text-sm font-semibold underline ${focus}`}>Edit<span className="sr-only"> {k}</span></button>
                </div>
              ))}
            </dl>
          )}
        </div>
        <div className="mt-8 flex items-center gap-3">
          <button type="button" onClick={() => (step === 0 ? onExit() : setStep(step - 1))} className={btn2}>Back</button>
          <button type="submit" className={`${btn} ml-auto`}>{step === last ? "Generate my blueprint" : "Continue"}</button>
        </div>
      </form>
    </section>
  );
}

