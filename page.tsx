function useReducedMotion() {
  const [reduced, setReduced] = useState(false);
  useEffect(() => {
    const m = window.matchMedia("(prefers-reduced-motion: reduce)");
    const update = () => setReduced(m.matches);
    update();
    m.addEventListener("change", update);
    return () => m.removeEventListener("change", update);
  }, []);
  return reduced;
}

/** Synthesised pencil scratch. Created only after the user presses the sound button. */
function useSound() {
  const ctxRef = useRef<AudioContext | null>(null);
  const gainRef = useRef<GainNode | null>(null);
  const filterRef = useRef<BiquadFilterNode | null>(null);
  const onRef = useRef(false);
  const idle = useRef(0);
  const [enabled, setEnabled] = useState(false);

  useEffect(
    () => () => {
      window.clearTimeout(idle.current);
      void ctxRef.current?.close();
      ctxRef.current = null;
    },
    []
  );

  const toggle = useCallback(() => {
    const next = !onRef.current;
    onRef.current = next;
    setEnabled(next);
    if (!next) {
      const c = ctxRef.current;
      if (c) gainRef.current?.gain.setTargetAtTime(0, c.currentTime, 0.02);
      return;
    }
    if (!ctxRef.current) {
      const Ctor =
        window.AudioContext ||
        (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
      const ctx = new Ctor();
      const buf = ctx.createBuffer(1, ctx.sampleRate * 2, ctx.sampleRate);
      const d = buf.getChannelData(0);
      for (let i = 0; i < d.length; i++) d[i] = Math.random() * 2 - 1;
      const src = ctx.createBufferSource();
      src.buffer = buf;
      src.loop = true;
      const filter = ctx.createBiquadFilter();
      filter.type = "bandpass";
      filter.frequency.value = 3500;
      filter.Q.value = 0.8;
      const gain = ctx.createGain();
      gain.gain.value = 0;
      src.connect(filter).connect(gain).connect(ctx.destination);
      src.start();
      ctxRef.current = ctx;
      gainRef.current = gain;
      filterRef.current = filter;
    }
    void ctxRef.current.resume();
  }, []);

  const scratch = useCallback((speed: number) => {
    const ctx = ctxRef.current;
    const gain = gainRef.current;
    const filter = filterRef.current;
    if (!onRef.current || !ctx || !gain || !filter) return;
    gain.gain.setTargetAtTime(Math.min(0.08, speed * 0.03), ctx.currentTime, 0.03);
    filter.frequency.setTargetAtTime(2500 + Math.min(speed, 4) * 600, ctx.currentTime, 0.05);
    window.clearTimeout(idle.current);
    idle.current = window.setTimeout(() => gain.gain.setTargetAtTime(0, ctx.currentTime, 0.04), 90);
  }, []);

  const silence = useCallback(() => {
    window.clearTimeout(idle.current);
    const c = ctxRef.current;
    if (c) gainRef.current?.gain.setTargetAtTime(0, c.currentTime, 0.02);
  }, []);

  return { enabled, toggle, scratch, silence };
}

