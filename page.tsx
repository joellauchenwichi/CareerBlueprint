/** Subtle pencil trail on one fixed canvas. Only mouse movement draws; touch and scroll are untouched. */
function PenLayer({ active, onSpeed }: { active: boolean; onSpeed: (s: number) => void }) {
  const ref = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const canvas = ref.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    type S = { x1: number; y1: number; x2: number; y2: number; t: number };
    let segs: S[] = [];
    let raf = 0;
    let prev: { x: number; y: number; t: number } | null = null;
    const LIFE = 2200;

    const resize = () => {
      const dpr = window.devicePixelRatio || 1;
      canvas.width = window.innerWidth * dpr;
      canvas.height = window.innerHeight * dpr;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    };
    const clear = () => ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);
    resize();
    window.addEventListener("resize", resize);

    const frame = () => {
      const now = performance.now();
      clear();
      segs = segs.filter((s) => now - s.t < LIFE);
      ctx.lineCap = "round";
      ctx.lineWidth = 1;
      ctx.strokeStyle = getComputedStyle(canvas).getPropertyValue("--accent").trim() || "#1F4FA5";
      for (const s of segs) {
        ctx.globalAlpha = 0.35 * (1 - (now - s.t) / LIFE);
        ctx.beginPath();
        ctx.moveTo(s.x1, s.y1);
        ctx.lineTo(s.x2, s.y2);
        ctx.stroke();
      }
      ctx.globalAlpha = 1;
      raf = segs.length ? requestAnimationFrame(frame) : 0;
    };

    const onMove = (e: PointerEvent) => {
      if (e.pointerType !== "mouse") return;
      const now = performance.now();
      if (prev) {
        const d = Math.hypot(e.clientX - prev.x, e.clientY - prev.y);
        if (d < 3) return;
        onSpeed(d / Math.max(1, now - prev.t));
        segs.push({ x1: prev.x, y1: prev.y, x2: e.clientX, y2: e.clientY, t: now });
        if (segs.length > 300) segs.splice(0, segs.length - 300);
        if (!raf) raf = requestAnimationFrame(frame);
      }
      prev = { x: e.clientX, y: e.clientY, t: now };
    };
    const onLeave = () => {
      prev = null;
    };

    if (active) {
      window.addEventListener("pointermove", onMove, { passive: true });
      document.addEventListener("mouseleave", onLeave);
    } else {
      clear();
    }
    return () => {
      window.removeEventListener("resize", resize);
      window.removeEventListener("pointermove", onMove);
      document.removeEventListener("mouseleave", onLeave);
      cancelAnimationFrame(raf);
      clear();
    };
  }, [active, onSpeed]);

  return <canvas ref={ref} aria-hidden className="pointer-events-none fixed inset-0 z-[1] h-full w-full" />;
}

/** A friendly eye. The pupil follows the pointer anywhere on screen. Click, tap or focus it to read the label. */
function Mascot() {
  const btnRef = useRef<HTMLButtonElement>(null);
  const pupilRef = useRef<SVGGElement>(null);
  const blinkTimer = useRef(0);
  const [near, setNear] = useState(false);
  const [pinned, setPinned] = useState(false);
  const [focused, setFocused] = useState(false);
  const [blink, setBlink] = useState(false);
  const open = near || pinned || focused;

  useEffect(() => {
    const onMove = (e: PointerEvent) => {
      const r = btnRef.current?.getBoundingClientRect();
      const g = pupilRef.current;
      if (!r || !g) return;
      const dx = e.clientX - (r.left + r.width / 2);
      const dy = e.clientY - (r.top + r.height / 2);
      const d = Math.hypot(dx, dy) || 1;
      const k = Math.min(1, d / 120);
      g.style.transform = `translate(${(dx / d) * k * 7}px, ${(dy / d) * k * 4.5}px)`;
      if (e.pointerType === "mouse") setNear(d < 90);
    };
    window.addEventListener("pointermove", onMove, { passive: true });
    window.addEventListener("pointerdown", onMove, { passive: true });
    return () => {
      window.removeEventListener("pointermove", onMove);
      window.removeEventListener("pointerdown", onMove);
      window.clearTimeout(blinkTimer.current);
    };
  }, []);

  return (
    <div className="fixed bottom-24 right-4 z-30 md:bottom-5">
      {open && (
        <div role="status" className="absolute bottom-full right-0 mb-2 whitespace-nowrap rounded-sm border border-[var(--line)] bg-[var(--surface)] px-3 py-1.5 text-xs font-semibold shadow-sm">
          Keeping an eye on your progress
        </div>
      )}
      <button
        ref={btnRef}
        type="button"
        aria-pressed={pinned}
        aria-label="Keeping an eye on your progress. Press to keep the label showing."
        onClick={() => {
          setPinned((v) => !v);
          setBlink(true);
          window.clearTimeout(blinkTimer.current);
          blinkTimer.current = window.setTimeout(() => setBlink(false), 160);
        }}
        onFocus={() => setFocused(true)}
        onBlur={() => setFocused(false)}
        className={`grid h-14 w-14 place-items-center rounded-full border border-[var(--line)] bg-[var(--surface)] shadow-sm transition-transform hover:scale-105 ${focus}`}
      >
        <svg viewBox="0 0 48 48" className="h-10 w-10" aria-hidden>
          <g style={{ transformOrigin: "24px 24px", transform: blink ? "scaleY(0.1)" : "scaleY(1)", transition: "transform 120ms ease" }}>
            <path d="M4 24c5-9 12-13 20-13s15 4 20 13c-5 9-12 13-20 13S9 33 4 24z" fill="var(--bg)" stroke="var(--accent)" strokeWidth="2.4" strokeLinejoin="round" />
            <g ref={pupilRef} style={{ transition: "transform 90ms ease-out" }}>
              <circle cx="24" cy="24" r="8" fill="var(--ink)" />
              <circle cx="26.5" cy="21.5" r="2.2" fill="var(--bg)" />
            </g>
          </g>
        </svg>
      </button>
    </div>
  );
}