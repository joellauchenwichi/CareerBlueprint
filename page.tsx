const clamp = (v: number, a: number, b: number) => Math.max(a, Math.min(b, v));

/** Hands-on hero: drag milestone tags around the sheet, click the sheet to pin a milestone. */
function HeroBoard({ onSend }: { onSend: (texts: string[]) => void }) {
  const boardRef = useRef<HTMLDivElement>(null);
  const [tags, setTags] = useState<HeroTag[]>(HERO_TAGS);
  const [pins, setPins] = useState<{ x: number; y: number }[]>([]);
  const drag = useRef<{ id: string; ox: number; oy: number } | null>(null);
  const pinned = tags.filter((t) => t.pinned);

  const pct = (cx: number, cy: number) => {
    const r = boardRef.current?.getBoundingClientRect();
    return r ? { x: ((cx - r.left) / r.width) * 100, y: ((cy - r.top) / r.height) * 100 } : { x: 50, y: 50 };
  };
  const place = (id: string, x: number, y: number) =>
    setTags((ts) => ts.map((t) => (t.id === id ? { ...t, x: clamp(x, 0, 78), y: clamp(y, 0, 90) } : t)));
  const addPin = (x: number, y: number) => setPins((ps) => (ps.length >= 12 ? ps : [...ps, { x, y }]));
  const addNote = (text: string) =>
    setTags((ts) =>
      ts.length >= 20 ? ts : [...ts, { id: `n${Date.now()}`, text, x: 8 + Math.random() * 45, y: 6 + Math.random() * 80, r: Math.round(Math.random() * 8 - 4) }]
    );
  const togglePin = (id: string) => setTags((ts) => ts.map((t) => (t.id === id ? { ...t, pinned: !t.pinned } : t)));

  return (
    <div className="w-full max-w-md md:max-w-xl md:flex-1">
      <div className="mb-2 flex items-center justify-between text-[11px] font-extrabold uppercase tracking-wider">
        <span>Sheet 01</span>
        <span aria-live="polite">Pins {pins.length}/12</span>
        <span className="flex gap-3">
          <button type="button" onClick={() => addPin(10 + Math.random() * 80, 10 + Math.random() * 80)} className={`underline ${focus}`}>Add pin</button>
          <button type="button" onClick={() => { setPins([]); setTags(HERO_TAGS); }} className={`underline ${focus}`}>Reset</button>
        </span>
      </div>
      <div
        ref={boardRef}
        onClick={(e) => {
          const q = pct(e.clientX, e.clientY);
          addPin(q.x, q.y);
        }}
        className={`${card} relative h-[22rem] cursor-crosshair overflow-hidden md:h-[26rem]`}
        style={{ backgroundImage: "linear-gradient(var(--grid2) 1px,transparent 1px),linear-gradient(90deg,var(--grid2) 1px,transparent 1px)", backgroundSize: "32px 32px" }}
      >
        {tags.map((t, i) => (
          <div
            key={t.id}
            onClick={(e) => e.stopPropagation()}
            className="rise absolute flex items-start"
            style={{ left: `${t.x}%`, top: `${t.y}%`, rotate: `${t.r}deg`, animationDelay: `${300 + i * 90}ms` }}
          >
            <button
              type="button"
              aria-label={`${t.text}. ${t.pinned ? "Pinned in place." : "Drag to move, or use the arrow keys."}`}
              onPointerDown={(e) => {
                if (t.pinned) return;
                e.currentTarget.setPointerCapture(e.pointerId);
                const q = pct(e.clientX, e.clientY);
                drag.current = { id: t.id, ox: q.x - t.x, oy: q.y - t.y };
              }}
              onPointerMove={(e) => {
                const d = drag.current;
                if (!d || d.id !== t.id) return;
                const q = pct(e.clientX, e.clientY);
                place(t.id, q.x - d.ox, q.y - d.oy);
              }}
              onPointerUp={() => (drag.current = null)}
              onPointerCancel={() => (drag.current = null)}
              onKeyDown={(e) => {
                if (t.pinned) return;
                const step = 3;
                if (e.key === "ArrowLeft") place(t.id, t.x - step, t.y);
                else if (e.key === "ArrowRight") place(t.id, t.x + step, t.y);
                else if (e.key === "ArrowUp") place(t.id, t.x, t.y - step);
                else if (e.key === "ArrowDown") place(t.id, t.x, t.y + step);
                else return;
                e.preventDefault();
              }}
              className={`touch-none select-none border-2 border-[var(--ink)] bg-[var(--surface)] px-3 py-1.5 text-sm font-extrabold shadow-[3px_3px_0_var(--ink)] hover:shadow-[4px_4px_0_var(--ink)] ${t.pinned ? "cursor-default" : "cursor-grab active:cursor-grabbing"} ${focus}`}
            >
              {t.text}
            </button>
            <button
              type="button"
              aria-pressed={!!t.pinned}
              aria-label={`${t.pinned ? "Unpin" : "Pin"} ${t.text}`}
              onClick={() => togglePin(t.id)}
              className={`-ml-2 -mt-2 h-5 w-5 rounded-full border-2 border-[var(--ink)] ${focus}`}
              style={{ background: t.pinned ? ORANGE : "var(--surface)" }}
            />
          </div>
        ))}
        {pins.map((q, i) => (
          <span key={i} aria-hidden className="pop pointer-events-none absolute -ml-3 -mt-3 grid h-6 w-6 place-items-center rounded-full border-2 border-[var(--ink)] bg-[var(--accent)] text-[11px] font-extrabold text-[var(--bg)]" style={{ left: `${q.x}%`, top: `${q.y}%` }}>
            {i + 1}
          </span>
        ))}
      </div>
      <p className="mt-2 text-xs text-[var(--muted)]">Drag the tags around. Click the sheet to pin a milestone. Use the dot on a tag to pin it in place.</p>
      <div className="mt-4"><NoteComposer id="hero-note" placeholder="Write your own milestone, then pin it" button="Add note" onAdd={addNote} /></div>
      <button type="button" disabled={pinned.length === 0} onClick={() => onSend(pinned.map((t) => t.text))} className={`${btn2} mt-3`}>
        Send pinned notes to Progress ({pinned.length})
      </button>
    </div>
  );
}

