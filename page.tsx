const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const PW_MIN = 8;

function AuthScreen({ onAuthed }: { onAuthed: (token: string, user: User) => Promise<void> }) {
  const [mode, setMode] = useState<"signup" | "login">("signup");
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [show, setShow] = useState(false);
  const [errs, setErrs] = useState<{ email?: string; password?: string; form?: string }>({});
  const [busy, setBusy] = useState(false);
  const signup = mode === "signup";

  const submit = async (e: FormEvent) => {
    e.preventDefault();
    if (busy) return;
    const em = email.trim().toLowerCase();
    const next: typeof errs = {};
    if (!EMAIL_RE.test(em)) next.email = "Enter a valid email address.";
    if (!password) next.password = "Enter your password.";
    else if (signup && password.length < PW_MIN) next.password = `Use at least ${PW_MIN} characters.`;
    setErrs(next);
    if (next.email || next.password) return;

    setBusy(true);
    try {
      const res = await api<{ token: string; user: User }>(`/api/auth/${mode}`, {
        method: "POST",
        body: JSON.stringify({ email: em, password }),
      });
      await onAuthed(res.token, res.user);
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Something went wrong. Try again.";
      setErrs({ form: msg });
      setBusy(false);
    }
  };

  const switchMode = () => {
    setMode(signup ? "login" : "signup");
    setErrs({});
  };

  return (
    <section className="relative z-10 flex min-h-screen items-center justify-center px-6 py-12">
      <div className="w-full max-w-md">
        <div className="mb-6 flex items-center gap-3">
          <Logo />
          <h1 className="text-3xl font-bold tracking-[-0.03em]">Career Blueprint</h1>
        </div>
        <form onSubmit={submit} noValidate className={`${card} p-6 md:p-8`}>
          <h2 className="text-2xl font-extrabold">{signup ? "Create your account" : "Welcome back"}</h2>
          <p className="mt-2 text-sm leading-6 text-[var(--muted)]">
            {signup
              ? "Your answers, roadmap and progress are saved to your email, so you can come back and pick up where you left off."
              : "Sign in to see your roadmap and progress."}
          </p>

          <div className="mt-6 space-y-4">
            <Field id="auth-email" label="Email" error={errs.email}>
              <input
                id="auth-email"
                type="email"
                autoComplete="email"
                className={inputCls}
                value={email}
                placeholder="you@university.edu"
                onChange={(e) => setEmail(e.target.value)}
                aria-invalid={!!errs.email}
                aria-describedby={errs.email ? "auth-email-err" : undefined}
              />
            </Field>
            <Field id="auth-password" label="Password" error={errs.password}>
              <div className="flex gap-2">
                <input
                  id="auth-password"
                  type={show ? "text" : "password"}
                  autoComplete={signup ? "new-password" : "current-password"}
                  className={inputCls}
                  value={password}
                  placeholder={signup ? `At least ${PW_MIN} characters` : "Your password"}
                  onChange={(e) => setPassword(e.target.value)}
                  aria-invalid={!!errs.password}
                  aria-describedby={errs.password ? "auth-password-err" : undefined}
                />
                <button type="button" onClick={() => setShow((v) => !v)} aria-pressed={show} className={`${btn2} !px-3`}>
                  {show ? "Hide" : "Show"}
                </button>
              </div>
            </Field>
          </div>

          {errs.form && (
            <p role="alert" className="mt-4 rounded-md border border-[#E5484D] p-3 text-sm font-semibold text-[#E5484D]">{errs.form}</p>
          )}

          <button type="submit" disabled={busy} className={`${btn} mt-6 w-full`}>
            {busy ? "One moment" : signup ? "Create account" : "Sign in"}
          </button>

          <p className="mt-5 text-center text-sm text-[var(--muted)]">
            {signup ? "Already have an account?" : "New here?"}{" "}
            <button type="button" onClick={switchMode} className={`font-bold text-[var(--ink)] underline ${focus}`}>
              {signup ? "Sign in" : "Create an account"}
            </button>
          </p>
        </form>
      </div>
    </section>
  );
}

