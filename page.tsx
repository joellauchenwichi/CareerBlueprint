class ApiError extends Error {
  status: number;
  constructor(status: number, message: string) {
    super(message);
    this.status = status;
  }
}

async function api<T>(path: string, init: Omit<RequestInit, "headers"> = {}, token?: string | null): Promise<T> {
  let res: Response;
  try {
    res = await fetch(`${API}${path}`, {
      ...init,
      headers: { "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    });
  } catch {
    throw new ApiError(0, "Could not reach the server. Check your connection and try again.");
  }
  if (!res.ok) {
    let detail = `Request failed (${res.status})`;
    try {
      const j: unknown = await res.json();
      const d = (j as { detail?: unknown }).detail;
      if (typeof d === "string") detail = d;
    } catch {
      /* no JSON body */
    }
    throw new ApiError(res.status, detail);
  }
  return (await res.json()) as T;
}

function parseState(parsed: unknown): AppState {
  if (!parsed || typeof parsed !== "object") return defaultState;
  const o = parsed as Partial<Record<keyof AppState, unknown>>;
  const src = (o.profile && typeof o.profile === "object" ? o.profile : {}) as Record<string, unknown>;
  const merged: Record<string, unknown> = { ...defaultProfile };
  for (const k of Object.keys(defaultProfile)) {
    const d = (defaultProfile as Record<string, unknown>)[k];
    const v = src[k];
    if (k === "cvName") {
      if (typeof v === "string" || v === null) merged[k] = v;
    } else if (Array.isArray(d) ? Array.isArray(v) && v.every((x) => typeof x === "string") : typeof v === typeof d) {
      merged[k] = v;
    }
  }
  const done: Record<string, boolean> = {};
  if (o.done && typeof o.done === "object") {
    for (const [k, v] of Object.entries(o.done as Record<string, unknown>)) if (v === true) done[k] = true;
  }
  const doneAt: Record<string, number> = {};
  if (o.doneAt && typeof o.doneAt === "object") {
    for (const [k, v] of Object.entries(o.doneAt as Record<string, unknown>)) if (typeof v === "number" && done[k]) doneAt[k] = v;
  }
  const notes: Sticky[] = Array.isArray(o.notes)
    ? (o.notes as unknown[])
        .filter((x): x is Sticky => !!x && typeof (x as Sticky).id === "string" && typeof (x as Sticky).text === "string")
        .slice(0, 60)
    : [];
  return { profile: merged as Profile, done, doneAt, onboarded: o.onboarded === true, notes };
}

