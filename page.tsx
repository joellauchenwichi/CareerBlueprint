type SetFn = <K extends keyof Profile>(k: K, v: Profile[K]) => void;

const toggleIn = (list: string[], v: string) => (list.includes(v) ? list.filter((x) => x !== v) : [...list, v]);

function Chips({
  options, value, onChange, label, exclusive,
}: { options: string[]; value: string[]; onChange: (v: string[]) => void; label: string; exclusive?: string }) {
  return (
    <div role="group" aria-label={label} className="mt-3 flex flex-wrap gap-2">
      {options.map((o) => {
        const on = value.includes(o);
        return (
          <button
            key={o}
            type="button"
            aria-pressed={on}
            onClick={() => {
              if (exclusive && o === exclusive) onChange(on ? [] : [o]);
              else onChange(toggleIn(exclusive ? value.filter((x) => x !== exclusive) : value, o));
            }}
            className={`inline-flex items-center gap-1.5 rounded-full border px-3.5 py-2 text-sm font-semibold transition-colors ${on ? "pop" : ""} ${focus} ${
              on ? "border-[var(--accent)] bg-[var(--accent)] text-[var(--bg)]" : "border-[var(--line)] bg-[var(--surface)] text-[var(--ink)] hover:bg-[var(--tint)]"
            }`}
          >
            {on && <svg viewBox="0 0 24 24" className="h-3.5 w-3.5" fill="none" stroke="currentColor" strokeWidth="3" strokeLinecap="round" strokeLinejoin="round" aria-hidden><path d="M5 12.5l4.5 4.5L19 7" /></svg>}
            {o}
          </button>
        );
      })}
    </div>
  );
}

function Field({ id, label, optional, error, children }: { id: string; label: string; optional?: boolean; error?: string; children: ReactNode }) {
  return (
    <div>
      <label htmlFor={id} className="block text-sm font-bold">
        {label} {optional && <span className="font-medium text-[var(--muted)]">(optional)</span>}
      </label>
      <div className="mt-1.5">{children}</div>
      {error && <p id={`${id}-err`} role="alert" className="mt-1 text-xs font-semibold text-[#E5484D]">{error}</p>}
    </div>
  );
}

function TextIn({ id, label, value, onChange, placeholder, optional = true, area, error }: { id: string; label: string; value: string; onChange: (v: string) => void; placeholder?: string; optional?: boolean; area?: boolean; error?: string }) {
  const a11y = { "aria-invalid": !!error, "aria-describedby": error ? `${id}-err` : undefined, "aria-required": !optional };
  return (
    <Field id={id} label={label} optional={optional} error={error}>
      {area ? (
        <textarea id={id} rows={3} className={inputCls} value={value} placeholder={placeholder} onChange={(e) => onChange(e.target.value)} {...a11y} />
      ) : (
        <input id={id} className={inputCls} value={value} placeholder={placeholder} onChange={(e) => onChange(e.target.value)} {...a11y} />
      )}
    </Field>
  );
}

